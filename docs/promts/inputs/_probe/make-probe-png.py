"""Зонд «чи читає agy зображення»: PNG з відомим текстом і фігурою.

Без PIL — лише stdlib (zlib + struct), шрифт 5×7 задано нижче. Вихід детермінований:
той самий скрипт дає той самий файл. Відповідь, яку має дати модель, — у ANSWER.
"""

import struct
import sys
import zlib

TEXT = ["HART 4729", "KVITKA 18"]
ANSWER = "Текст: «HART 4729» і «KVITKA 18»; праворуч — червоне коло."

FONT = {
    "A": ["01110", "10001", "10001", "11111", "10001", "10001", "10001"],
    "H": ["10001", "10001", "10001", "11111", "10001", "10001", "10001"],
    "I": ["01110", "00100", "00100", "00100", "00100", "00100", "01110"],
    "K": ["10001", "10010", "10100", "11000", "10100", "10010", "10001"],
    "R": ["11110", "10001", "10001", "11110", "10100", "10010", "10001"],
    "T": ["11111", "00100", "00100", "00100", "00100", "00100", "00100"],
    "V": ["10001", "10001", "10001", "10001", "10001", "01010", "00100"],
    "1": ["00100", "01100", "00100", "00100", "00100", "00100", "01110"],
    "2": ["01110", "10001", "00001", "00010", "00100", "01000", "11111"],
    "4": ["00010", "00110", "01010", "10010", "11111", "00010", "00010"],
    "7": ["11111", "00001", "00010", "00100", "01000", "01000", "01000"],
    "8": ["01110", "10001", "10001", "01110", "10001", "10001", "01110"],
    "9": ["01110", "10001", "10001", "01111", "00001", "00010", "01100"],
    " ": ["00000"] * 7,
}
S = 8  # масштаб пікселя шрифту
W, H = 640, 220
WHITE, BLACK, RED = (255, 255, 255), (0, 0, 0), (220, 30, 30)

px = [[WHITE] * W for _ in range(H)]
for li, line in enumerate(TEXT):
    x0, y0 = 24, 30 + li * 90
    for ci, ch in enumerate(line):
        for r, row in enumerate(FONT[ch]):
            for c, bit in enumerate(row):
                if bit == "1":
                    for dy in range(S):
                        for dx in range(S):
                            px[y0 + r * S + dy][x0 + ci * 6 * S + c * S + dx] = BLACK
cx, cy, rad = 560, 110, 50
for y in range(H):
    for x in range(W):
        if (x - cx) ** 2 + (y - cy) ** 2 <= rad * rad:
            px[y][x] = RED

raw = b"".join(b"\x00" + bytes(v for p in row for v in p) for row in px)


def chunk(tag, data):
    return struct.pack(">I", len(data)) + tag + data + struct.pack(">I", zlib.crc32(tag + data))


png = b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", W, H, 8, 2, 0, 0, 0))
png += chunk(b"IDAT", zlib.compress(raw, 9)) + chunk(b"IEND", b"")
with open(sys.argv[1], "wb") as fh:
    fh.write(png)
