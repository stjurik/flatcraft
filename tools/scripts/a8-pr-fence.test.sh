#!/usr/bin/env bash
# a8-pr-fence.test.sh — доказ, що тіло draft PR лишається ДАНИМИ.
#
# Навіщо окремий набір. `a8-pr.yml` бере повідомлення коміту, яке написала
# модель, і кладе його в тіло PR. Єдине, що заважає тому тексту вилізти з
# code-block'а і намалювати в тілі PR фальшивий заголовок «перевірено» або
# посилання, — огорожа, ДОВША за будь-який ряд бектиків у повідомленні.
# Це межа безпеки, і до 2026-09-23 вона не мала жодного тесту: її довели
# один раз парсером CommonMark вручну. Спрощення циклу назад до фіксованих
# ``` нічого б не зробило червоним — а саме так вона вже одного разу й
# пробивалась (коміт 0b967ed).
#
# Що СПРАВЖНЄ: алгоритм витягається з самого `.github/workflows/a8-pr.yml`,
# рядок у рядок. Тест не має власної копії — інакше він доводив би свою
# копію, а не те, що виконається в Actions. Звідси дві половини: структурна
# (цикл на місці й саме такий) і поведінкова (витягнутий код тримає ворожі
# входи). Одна без іншої нічого не доводить.
#
# Запуск: tools/scripts/a8-pr-fence.test.sh
set -uo pipefail

HERE="$(cd "$(dirname "$0")" && pwd)"
WF="$HERE/../../.github/workflows/a8-pr.yml"
fail=0
ok() { echo "✓ $1"; }
bad() {
  echo "✗ $1"
  fail=1
}

if [[ ! -f "$WF" ]]; then
  echo "✗ немає $WF — нічого перевіряти"
  exit 1
fi

# ─── Структурна половина ──────────────────────────────────────────────────
# Огорожа мусить РОСТИ. Фіксований рядок бектиків — саме та вада, що вже була.
FENCE_INIT="$(grep -hE "^[[:space:]]*fence='\`+'[[:space:]]*$" "$WF" | head -1)"
FENCE_LOOP="$(grep -hE '^[[:space:]]*while \[\[ "\$msg" == \*"\$fence"\* \]\][[:space:]]*; do' "$WF" | head -1)"

if [[ -n "$FENCE_INIT" && -n "$FENCE_LOOP" ]]; then
  ok "огорожа росте циклом, а не задана фіксованим рядком бектиків"
else
  bad "у a8-pr.yml немає циклу росту огорожі — текст моделі зможе закрити блок"
fi

# Відкриття і закриття мусять бути ОДНІЄЮ змінною. Закриття літералом ``` при
# вирослому відкритті не закриє блок, і тіло PR поїде розміткою.
if grep -qE '^[[:space:]]*echo "\$\{fence\}text"' "$WF" && grep -qE '^[[:space:]]*echo "\$fence"' "$WF"; then
  ok "відкриття і закриття блоку — та сама змінна \$fence"
else
  bad "відкриття/закриття блоку не через \$fence — довжини можуть розійтись"
fi

# `fence` присвоюється РІВНО двічі: ініціалізація і крок циклу. Третє
# присвоєння після циклу (наприклад, скидання назад до ```) Actions виконав би,
# а поведінкова половина нижче його не побачила б — вона бере лише перший
# `fence=` і перший цикл. Знайдено незалежним рев'ю agy 2026-09-23.
assigns="$(grep -cE '(^|[[:space:];])fence=' "$WF")"
if [[ "$assigns" -eq 2 ]]; then
  ok "fence присвоюється рівно двічі — після циклу його не перевизначають"
else
  bad "fence присвоюється $assigns раз(и) замість 2 — огорожу можуть скинути після циклу"
fi

# Порядок: відкрити → вивести повідомлення → закрити. Самої наявності трьох
# рядків мало — переставлені місцями, вони дали б зламане тіло при зеленому
# тесті. Теж із рев'ю agy.
o_open="$(grep -nE '^[[:space:]]*echo "\$\{fence\}text"' "$WF" | head -1 | cut -d: -f1)"
o_msg="$(grep -nE "^[[:space:]]*printf '%s\\\\n' \"\\\$msg\"" "$WF" | head -1 | cut -d: -f1)"
o_close="$(grep -nE '^[[:space:]]*echo "\$fence"' "$WF" | head -1 | cut -d: -f1)"
if [[ -n "$o_open" && -n "$o_msg" && -n "$o_close" ]] && ((o_open < o_msg && o_msg < o_close)); then
  ok "порядок у тілі: відкриття → повідомлення → закриття"
else
  bad "порядок відкриття/повідомлення/закриття порушено (($o_open, $o_msg, $o_close))"
fi

# ─── Анти-інжекція ────────────────────────────────────────────────────────
# `${{ }}` усередині `run:` підставляється ДО запуску shell, тобто текст,
# підконтрольний моделі, став би кодом. Ім'я гілки має йти через env.
RUN_BLOCK="$(awk '/^[[:space:]]*run: \|/{f=1;next} f&&/^[[:space:]]*-[[:space:]]/{f=0} f' "$WF")"
# Контроль захоплення: якщо awk узяв не той шматок (додали крок після run:,
# змінили відступи), перевірка нижче мовчки доводила б порожнечу.
if ! grep -q 'gh pr create' <<<"$RUN_BLOCK"; then
  bad "run-блок витягнуто неправильно — у ньому немає 'gh pr create'"
elif grep -q '\${{' <<<"$RUN_BLOCK"; then
  bad "у run-блоці є \${{ }} — це script injection з тексту, який пише модель"
else
  ok "у run-блоці немає жодної інтерполяції \${{ }} — вхід іде через env"
fi

# ─── Поведінкова половина ─────────────────────────────────────────────────
# Витягнутий з воркфлоу код запускається на ворожих повідомленнях.
T="$(mktemp -d)"
trap 'rm -rf "$T"' EXIT
{
  echo 'msg="$(cat)"'
  echo "$FENCE_INIT"
  echo "$FENCE_LOOP"
  echo 'printf "%s" "$fence"'
} >"$T/fence.sh"

fence_for() { printf '%s' "$1" | bash "$T/fence.sh"; }

# Головний інваріант: огорожа не зустрічається в тексті. Якщо зустрічається —
# CommonMark закриє блок на ній, і залишок тексту стане розміткою тіла PR.
check() { # check <назва> <повідомлення>
  local name="$1" m="$2" f
  f="$(fence_for "$m")"
  if [[ ${#f} -lt 3 ]]; then
    bad "$name: огорожа коротша за 3 бектики (${#f}) — це взагалі не code block"
  elif [[ "$m" == *"$f"* ]]; then
    bad "$name: огорожа (${#f}) зустрічається в тексті — блок закриється зарано"
  else
    ok "$name: огорожа ${#f} бектиків, у тексті не зустрічається"
  fi
}

check "текст без бектиків" 'звичайний коміт'
check "порожній текст" ''
check "рівно три бектики" $'до\n```\n## ФАЛЬШИВИЙ ЗАГОЛОВОК\nпісля'
check "шість бектиків" $'x\n``````\n**втеча**'
check "рядок дорівнює огорожі" '```text'
check "бектики всередині рядка" 'див. ```sh``` нижче'
check "зростаюча драбина" $'```\n````\n`````\n``````\n```````'

# Контроль сили набору: підроблена «фіксована» огорожа мусить впасти на тому
# самому вході. Без цієї перевірки набір доводив би лише свою власну логіку.
cat >"$T/fixed.sh" <<'FIXED'
msg="$(cat)"
fence='```'
printf "%s" "$fence"
FIXED
bad_fence="$(printf '%s' $'x\n```\ny' | bash "$T/fixed.sh")"
if [[ $'x\n```\ny' == *"$bad_fence"* ]]; then
  ok "контроль: фіксована огорожа справді пробивається тим самим входом"
else
  bad "контроль не спрацював — перевірка вище нічого не доводить"
fi

if ((fail)); then
  echo "Провалено."
  exit 1
fi
echo "Усі тести пройдено."
