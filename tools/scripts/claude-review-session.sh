#!/usr/bin/env bash
# claude-review-session.sh — контрприклади до ризикового PR окремою сесією Claude Code,
# коли ліміт Opus в agy на межі (рішення yurii 2026-09-27; CLAUDE.md §0 п.2 — шлях
# «окрема сесія Claude, не та, що писала код»). Хто дає контрприклади — agy чи ця
# сесія — каже tools/scripts/agy-opus-budget.sh.
#
# ЧОМУ СКРИПТ, А НЕ КОМАНДА В ДОКУМЕНТІ. Сесія-рецензент читає diff, у якому може
# стояти будь-який текст, і її відповідь іде в PR дослівно. Тож вона мусить бути
# обмежена читанням — кожен раз, а не коли оркестратор не забув прапорець.
# Прапорці звірено з `claude --help` і перевірено запуском 2026-09-27 (Claude Code
# 2.1.283): з ними сесія
#   --tools Read,Grep,Glob    не має інструментів, що виконують команди чи пишуть файли;
#   --permission-mode dontAsk не питає — усе, що потребує дозволу, відхиляється;
#   --restricted              читає лише в робочому дереві, ігнорує локальні дозволи
#                             (накопичені «більше не питати» сюди не потрапляють);
#   deny Read(**/.env*)       не читає .env навіть у робочому дереві.
# Без --restricted версія Claude Code не підходить — відмова, а не запуск без обмежень.
#
# Сесія окрема й свіжа (--no-session-persistence): контексту автора в неї немає.
# stdin — /dev/null: інакше `claude -p` 3 с чекає даних на stdin (попередження в
# першому ж запуску 2026-09-27), а в конвеєрі прочитав би чужий вивід як частину промпту.
# Витрачає ліміт підписки Claude — той самий, на якому працює оркестратор.
#
# Використання (з кореня worktree гілки PR):
#   bash tools/scripts/claude-review-session.sh <абсолютний шлях до файла контексту> [модель]
# Файл контексту — як для agy (orchestrator-autonomy.md §3.3 п.2): що рецензувати, які
# файли, питання; лежить у робочому дереві. Модель — за замовчуванням opus.
# Рецензія — у stdout; exit — як у claude; exit 2 — відмова до запуску.
set -euo pipefail

CTX="${1:-}"
MODEL="${2:-opus}"
refuse() {
  echo "відмова: $1 — сесію не запущено" >&2
  exit 2
}

(($# >= 1 && $# <= 2)) || refuse "використання: $(basename "$0") <абсолютний шлях до файла контексту> [модель]"
[[ "$CTX" == /* ]] || refuse "шлях до файла контексту має бути абсолютним: $CTX"
[[ -f "$CTX" ]] || refuse "немає файла контексту $CTX"
ROOT="$(git rev-parse --show-toplevel 2>/dev/null)" || refuse "запускати з worktree гілки PR"
[[ "$CTX" == "$ROOT"/* ]] ||
  refuse "файл контексту поза робочим деревом $ROOT — сесія з --restricted його не прочитає"
[[ "$MODEL" =~ ^[a-z0-9.-]+$ ]] || refuse "дивна назва моделі: $MODEL"

help="$(claude --help 2>&1)" || refuse "claude не запускається"
for flag in --restricted --tools --permission-mode --no-session-persistence --settings; do
  [[ "$help" == *"$flag"* ]] || refuse "ця версія Claude Code не знає $flag — оновіть; без нього сесія не обмежена читанням"
done

PROMPT="Ти — незалежний рецензент чужого PR; автор — інша сесія. Твоя роль — лише контрприклади: вхід чи сценарій, на якому код поводиться не так, як заявлено. Прочитай файл $CTX інструментом Read і виконай завдання з нього. Інструментів для команд і запису в тебе немає — не намагайся. Кожне твердження — з посиланням файл:рядок; чого не перевірив — пиши «НЕ ПЕРЕВІРЕНО». Відповідь — лише текст рецензії."

cd "$ROOT"
exec claude -p "$PROMPT" \
  --model "$MODEL" \
  --tools Read,Grep,Glob \
  --permission-mode dontAsk \
  --restricted \
  --no-session-persistence \
  --settings '{"permissions":{"deny":["Read(**/.env*)"]}}' \
  --output-format text </dev/null
