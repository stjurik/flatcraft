#!/usr/bin/env bash
# agy-stats-summary.sh — поріг довіри agy окремо для кожної моделі.
#
# ЧОМУ СКРИПТ, А НЕ ПІДРАХУНОК РУКАМИ. Число потрібне щодня (звіт yurii,
# orchestrator-autonomy.md §5), а ручний підрахунок 2026-09-23 уже раз
# розбився: `\|` усередині клітинки зсунув колонки, і модель прочиталась як
# шматок тексту задачі. Ручна дія, що повторюється, стає скриптом (CLAUDE.md §0 п.5).
#
# ЩО РАХУЄ. Вікно — виклики, датовані не раніше AGY_WINDOW_START (дефолт
# 2026-09-15, коли поріг зареєстровано, CLAUDE.md §0 п.2), без позначки
# «не зараховано» (виклик без тверджень: timeout, зонд). Для кожної моделі:
# скільки викликів у вікні, скільки з них мали ≥1 вигаданий факт, частка,
# сума вигадок і вердикт. Межа — 10 викликів і 50%: якщо частка НЕ нижче 50%,
# модель іде з ролі Рев'юера в Розвідника (формулювання CLAUDE.md §0 п.2).
#
# Модель береться з колонки журналу як є. Її джерело — рядок логу agy
# `Propagating selected model override … label="…"` (orchestrator-autonomy.md §3),
# тож «Gemini 3.1 Pro (High)» і «невідомо» — різні моделі, і це правильно:
# виклик без підтвердженої моделі не має права покращувати чужу статистику.
#
# Використання: tools/scripts/agy-stats-summary.sh [журнал]
set -euo pipefail

FILE="${1:-$(git rev-parse --show-toplevel)/docs/promts/inputs/agy-stats.md}"
WINDOW_START="${AGY_WINDOW_START:-2026-09-15}"
[[ -f "$FILE" ]] || {
  echo "немає журналу: $FILE" >&2
  exit 2
}

echo "| Модель | Викликів усього | У вікні | З вигадками | Частка | Вигадок | Знахідок | Вердикт |"
echo "| ------ | --------------- | ------- | ----------- | ------ | ------- | -------- | ------- |"

# `\|` — екранований символ усередині клітинки, не межа колонки. Замінюємо
# його на символ, якого в журналі немає, ДО розбиття на колонки.
sed 's/\\|/\x1f/g' "$FILE" | awk -F'|' -v ws="$WINDOW_START" '
  function trim(s) { gsub(/^[ \t]+|[ \t]+$/, "", s); return s }
  /^\| [0-9]{4}-[0-9]{2}-[0-9]{2} / {
    date = trim($2); model = trim($4); fab = trim($8)
    # Число вигадок — перше **N** у клітинці; без нього виклик не оцінено.
    has_k = match(fab, /\*\*[0-9]+\*\*/)
    k = has_k ? substr(fab, RSTART + 2, RLENGTH - 4) + 0 : 0
    # Сумнів рахується проти моделі (рішення yurii 2026-09-23). Непідтверджена
    # модель пишеться «невідомо → <модель за замовчуванням у момент виклику>».
    # Із вигадками — іде в рахунок тієї моделі; чистий — не зараховується
    # нікому, бо покращив би статистику, якої не заслужив.
    # Написання не міняє суті: «Невідомо» з великої і стрілка без пробілів —
    # та сама непідтверджена модель (рецензія Gemini 3.1 Pro, 2026-09-23).
    # УВАГА: у цьому awk-блоці не можна писати апостроф — програма стоїть в
    # одинарних лапках bash, і апостроф її обриває (зламало скрипт 2026-09-23).
    if (model ~ /^[Нн]евідомо/) {
      if (k == 0) next
      arrow = index(model, "→")
      named = arrow ? trim(substr(model, arrow + length("→"))) : ""
      if (named == "") {
        printf "відмова: %s — невідомий виклик із вигадками, але модель за замовчуванням не названа; очікую «невідомо → <модель>»\n", date > "/dev/stderr"
        refuse = 1
        next
      }
      model = named
    }
    if (!(model in total)) order[++n] = model
    total[model]++
    if (date < ws) next
    # Маркер — лише ПОВНА фраза і лише в колонці вигадок, де її ставить
    # журнал. Слова «не зараховано» в описі задачі (рецензія Gemini 2026-09-23)
    # чи у вільному тексті тієї ж колонки («не зараховано вигадкою», справжній
    # журнал 2026-09-24) виклик із вікна не викидають.
    # Маркер — для викликів БЕЗ тверджень. Вигадки поруч із ним — суперечність:
    # мовчки прибрати їх із вікна означало б дати вигадкам зникнути.
    if (index(fab, "У вікно OQ-35 не зараховано")) {
      if (k > 0) {
        printf "відмова: %s — %d вигадок у рядку з позначкою «не зараховано»; позначка лише для викликів без тверджень\n", date, k > "/dev/stderr"
        refuse = 1
      }
      next
    }
    if (!has_k) next
    win[model]++
    sum[model] += k
    if (k > 0) bad[model]++
    # Справжні знахідки (рішення yurii 2026-09-24) — остання колонка, щоб не
    # зсунути наявні. Число на початку клітинки, звичайне чи жирне. Рядки до
    # появи колонки значення не мають: це «—», а не нуль.
    real = trim($9)
    if (match(real, /^\**[0-9]+/)) {
      digits = substr(real, RSTART, RLENGTH)
      gsub(/\*/, "", digits)
      rsum[model] += digits + 0
      has_real[model] = 1
    }
  }
  END {
    for (i = 1; i <= n; i++) {
      m = order[i]; w = win[m] + 0; b = bad[m] + 0
      pct = w ? int(b * 100 / w + 0.5) : 0
      if (w < 10) verdict = "рано судити (" w "/10)"
      else if (pct >= 50) verdict = "→ Розвідник (частка не нижче 50%)"
      else verdict = "Рев'\''юер тримається"
      printf "| %s | %d | %d | %d | %s | %d | %s | %s |\n", m, total[m], w, b, (w ? pct "%" : "—"), sum[m] + 0, (m in has_real ? rsum[m] + 0 : "—"), verdict
    }
    # Вигадки, яких нікому зарахувати, не мають права мовчки зникнути зі
    # статистики — це дірка в даних, і її треба закрити в журналі.
    if (refuse) exit 3
  }'
