# Текст правил для класу «правила-текст» — РЕГЕКСИ (не glob, як у RULES): у glob цього
# скрипта `*` захоплює й `/`, а `docs/promts/inputs/**` — дані (журнал, покази квоти), не
# правила. Лише документи; код, тести, CI (.github/), infra/, tools/, .claude/ сюди не
# потрапляють за побудовою.
TEXT_RULES=(
  '^CLAUDE\.md$'
  '^docs/03_DECISIONS\.md$'
  # docs/15 (промпти й ролі), docs/16 (автономні запуски), docs/17 (AI bugfix flow).
  '^docs/1[5-7]_[^/]+\.md$'
  # Реєстр відкритих рішень: тут зареєстровано поріг іспиту (OQ-35).
  '^docs/20_OPEN_DECISIONS\.md$'
  # Документи процесу: orchestrator-autonomy.md, ai-review-local.md, master-*.md… — лише
  # верхній рівень docs/promts/, без inputs/.
  '^docs/promts/[^/]+\.md$'
)
# Винятки з TEXT_RULES: документи docs/promts/, що є даними, а не правилами.
NOT_TEXT_RULES=(
  # Вхідні дані для чернеток agy (inbox-pull.sh) — контрприклад окремої сесії, #230.
  '^docs/promts/agy-inbox\.md$'
)

BASE="${REVIEW_CLASS_BASE:-origin/main}"
HEAD_REF="${REVIEW_CLASS_HEAD:-HEAD}"

# Правило «журнал лише дописується» — спільне з check-journals.sh (issue #169).
LIB="$(dirname "${BASH_SOURCE[0]}")/journal-rules.sh"
[[ -r "$LIB" ]] || {
  echo "відмова: немає $LIB — клас журналу не визначити" >&2
  exit 2
}
# shellcheck source=tools/scripts/journal-rules.sh
source "$LIB"

hits=()      # ризикові файли поза текстом правил
text_hits=() # файли тексту правил, що в RULES (ризикові, якщо виняток не діє)
texts=()     # усі файли тексту правил
other=0      # є файл, що не текст правил і не чисте дописування журналу
journal_touched=0 # змінено архів чи файл теки — журнал HEAD проганяється лічильниками
seen=0
while IFS= read -r f; do
  [[ -z "$f" ]] && continue
  seen=1
  # Шлях у лапках — git закодував незвичні символи (кирилицю — вісімковими кодами).
  # Розкодовуємо лише вісімкові коди; інше екранування — «не розпізнано», ризиковий.
  if [[ "$f" == \"*\" ]]; then
    raw="${f:1:${#f}-2}"
    if [[ "$raw" =~ ^([^\\\"]|\\[0-7]{3})*$ ]]; then
      f="$(printf '%b' "$(sed -E 's/\\([0-7]{3})/\\0\1/g' <<<"$raw")")"
    else
      hits+=("  шлях не розпізнано (сумнів проти PR): $f")
      continue
    fi
  fi
  if [[ "$f" == "$JOURNAL" ]]; then
    journal_touched=1
    journal_archive_violated &&
      hits+=("  правила й контракт: $f — старий зміст змінено, переставлено чи видалено, дописано щось, крім нових рядків таблиці в кінці, або архів змінено, коли в базі вже є файли теки agy-stats/ (або звірити не вдалося)")
    continue
  fi
  if [[ "$f" == "$QUOTA" ]]; then
    append_only_violated "$f" "$QUOTA_ROW_RE" &&
      hits+=("  правила й контракт: $f — старий зміст змінено, переставлено чи видалено, або дописано щось, крім нових рядків таблиці в кінці (або звірити не вдалося)")
    continue
  fi
  if [[ "$f" == "$JOURNAL_DIR"/* ]]; then
    journal_touched=1
    journal_dir_file_violated "$f" &&
      hits+=("  правила й контракт: $f — файл журналу: файл із бази змінено чи видалено, новий файл не такий, який прочитає лічильник (шапка, роздільник, рядки «| РРРР-ММ-ДД …»), або ім'я, тека чи розширення не ті (або звірити не вдалося)")
    continue
  fi
  is_text=0
  for t in "${TEXT_RULES[@]}"; do
    if [[ "$f" =~ $t ]]; then
      is_text=1
      for x in "${NOT_TEXT_RULES[@]}"; do [[ "$f" =~ $x ]] && is_text=0; done
      ((is_text)) && texts+=("  текст правил: $f")
      break
    fi
  done
  ((is_text)) || other=1
  for r in "${RULES[@]}"; do
    # shellcheck disable=SC2053 # шаблон навмисно без лапок — це glob
    if [[ "$f" == ${r#*|} ]]; then
      if ((is_text)); then text_hits+=("  ${r%%|*}: $f"); else hits+=("  ${r%%|*}: $f"); fi
      break
    fi
  done
done

if ((!seen)); then
  echo "відмова: порожній список змінених файлів — нічого класифікувати" >&2
  exit 2
fi
if ((journal_touched)) && why="$(journal_unreadable_at "$HEAD_REF")"; then
  hits+=("  правила й контракт: журнал іспиту в $HEAD_REF лічильники не прочитають — $why")
fi
if ((!${#hits[@]} && ${#texts[@]} && !other)); then
  echo "клас: правила-текст — лише текст правил: одна рецензія Gemini 3.8 Flash, без контрприкладів (CLAUDE.md §0 п.2, виняток 2026-10-11)"
  printf '%s\n' "${texts[@]}"
elif ((${#hits[@]} + ${#text_hits[@]})); then
  echo "клас: ризиковий — рецензія Gemini 3.8 Flash + контрприклади (CLAUDE.md §0 п.2)"
  all=("${hits[@]}" "${text_hits[@]}")
  printf '%s\n' "${all[@]}"
else
  echo "клас: звичайний — повна рецензія: одна, Gemini 3.8 Flash (CLAUDE.md §0 п.2)"
fi
