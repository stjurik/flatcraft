  # Знайдено першим пробним запуском claude-review-session.sh 2026-09-27.
  'дозволи й безпека|infra/discord/config/*'
  'дозволи й безпека|infra/discord/lib/permissions*'
  'дозволи й безпека|infra/discord/lib/apply*'
