#!/usr/bin/env bash
# review-class.sh — чи потрібна PR друга рецензія (контрприклади), за змінами файлів.
#
# ЧОМУ ЦЕ ІСНУЄ. Тижневий ліміт Opus в agy на 2026-09-27 — 15.5% (скріншот yurii).
# Рішення yurii того ж дня: дві рецензії — лише для ризикових PR, для решти повна
# рецензія — одна, від Gemini 3.8 Flash (CLAUDE.md §0 п.2). «Ризиковий» — п'ять
# категорій, названих yurii дослівно: дозволи й безпека; роль і демон A8; CI;
# експорт і валідатори §7; міграції. 2026-09-29 yurii додав ще дві («1а, 2а»): самі
# правила й контракт (CLAUDE.md, ADR, правила рецензії, журнал іспиту) — інакше PR,
# що послаблює вимогу другої рецензії, пройшов би з однією; і вся інфраструктура
# (`infra/**`) — у #139 саме там були бекапи, що ніколи не працювали. 2026-10-11 yurii
# зробив виняток (клас «правила-текст» нижче): PR, що змінює ЛИШЕ текст правил, — одна
# рецензія Flash, без контрприкладів, навіть якщо він послаблює вимогу другої рецензії.
# «Правила й контракт» роблять PR ризиковим, щойно поруч є код, тести, CI чи infra/.
# Якщо клас визначає судження оркестратора, то
# на кожному PR воно трохи інше, і правило перестає бути правилом. Тому клас дає
# перелік шляхів нижче, а зміна переліку — окремий, помітний рядок у PR.
#
# ЧОГО ЦЕ НЕ ДОВОДИТЬ. Клас рахується лише за шляхами. Новий файл поза переліком —
# «звичайний», навіть якщо за змістом він про безпеку. Такий файл додається в
# перелік тим самим PR, що його створює. Дописаний рядок журналу іспиту — теж завжди
# «звичайний», навіть якщо це вигаданий виклик чи «поправка» до старого: що рядок
# відповідає справжньому виклику, доводить лог agy (`--log-file`), а не цей скрипт. Те саме
# з датою рядка у файлі теки: датований заднім числом, він стане в іспиті раніше за пізніші
# виклики (порядок — journal_rows у journal-rules.sh), а скрипт дат не звіряє.
#
# Використання (перейменування — як видалення + додавання, щоб старий шлях теж
# рахувався; core.quotePath=false — щоб шлях з кирилицею прийшов як є):
#   git -c core.quotePath=false diff --name-only --no-renames origin/main...HEAD | bash tools/scripts/review-class.sh
# Без core.quotePath=false git бере такий шлях у лапки з вісімковими кодами
# ("…\320\267…"); скрипт розкодовує його сам, а шлях, якого не розкодував, — ризиковий.
#
# ЖУРНАЛ ІСПИТУ (`agy-stats.md`) — окремо. Його дописують майже в кожному PR (9 з 12
# останніх), а форматування таблиці при новому рядку перерівнює всі старі. Тож за
# назвою файла він зробив би ризиковими три чверті PR. Ризиково інше: змінити ЗМІСТ
# старих рядків чи правил у шапці — так модель можна «пропустити» через іспит заднім
# числом. Тому порівнюється зміст без вирівнювання (база — merge-base з
# REVIEW_CLASS_BASE, дефолт origin/main): старий зміст мусить лишитися в HEAD
# ДОСЛІВНО І В ТОМУ САМОМУ ПОРЯДКУ, а після нього — лише нові рядки викликів
# (`| РРРР-ММ-ДД | …`). Порядок важить: іспит — перші 10 викликів моделі за порядком
# у файлі, тож переставлений рядок змінює іспит (контрприклад окремої сесії, повторна
# рецензія #145). Новий абзац чи рядок-правило з `|` у шапці — теж ризиковий: правило
# «такі виклики не рахуються» можна не переписати, а дописати. Не вдалося звірити —
# ризиковий: сумнів іде проти PR.
#
# ПОКАЗИ КВОТИ (`agy-quota.md`) — так само: від них залежить, хто дає контрприклади,
# тож змінити старий показ — ризиково, дописати новий (`| РРРР-ММ-ДД ГГ:ХХ | …`) — ні.
#
# ТЕКА ЖУРНАЛУ (`docs/promts/inputs/agy-stats/`, файл на PR — рішення yurii 2026-10-11,
# #228). Порядок іспиту — порядок потрапляння в main (journal-rules.sh), тому файл, що вже
# є в базі, не змінюється взагалі, а архів — щойно в базі є хоч один файл теки: інакше
# дописаний рядок став би перед рядками пізніших файлів. Це ризиковий клас, як і видалення.
# Новий файл — «звичайний», якщо він такий, який прочитає лічильник: шапка як в архіві,
# роздільник, рядки `| РРРР-ММ-ДД …`, ім'я за JOURNAL_NAME_RE, верхній рівень теки; і якщо
# agy-stats-summary.sh та agy-opus-budget.sh на журналі HEAD виходять з 0, а прочитаних
# рядків стільки, скільки схожих на рядки викликів (journal_unreadable_at). Абзац-правило,
# примітка, чужа шапка — ризиковий. Правила — у journal-rules.sh, спільні з check-journals.sh.
#
# ЛИШЕ ТЕКСТ ПРАВИЛ (рішення yurii 2026-10-11, CLAUDE.md §0 п.2) — окремий клас
# `клас: правила-текст`: одна рецензія Gemini 3.8 Flash, без контрприкладів. Умова: КОЖЕН
# змінений файл або збігається з TEXT_RULES нижче (документи правил і процесу — без коду,
# тестів, CI, infra/, tools/, .claude/), або є чистим дописуванням журналу чи показів квоти
# (рядок журналу рецензії самого PR — не код і не правило; без цього виключення клас
# не настав би ніколи, бо рецензію PR пишуть у той самий PR). Хоч один інший файл — клас
# рахується як раніше, і файли правил з RULES знову роблять PR ризиковим.
# Новий клас — ПЕРШИМ рядком, а не позначкою другим: коду, що розбирає вивід, немає (grep
# по tools/, .github/, apps/, packages/, infra/ — 2026-10-11), читає його оркестратор за
# процедурою orchestrator-autonomy.md §3, і рядок сам каже, скільки рецензій. Позначка під
# «клас: ризиковий» суперечила б першому рядку, а під «клас: звичайний» — ховала б, що
# файли правил з RULES тут свідомо не рахуються.
#
# Вивід: перший рядок — `клас: ризиковий`, `клас: правила-текст` або `клас: звичайний`;
# далі — категорія і шлях для кожного ризикового файла (для «правила-текст» — кожен файл
# правил, що потрапив під виняток).
# exit 0 — класифіковано; exit 2 — порожній вхід (нічого класифікувати).
set -euo pipefail

