#!/usr/bin/env bash
# agy-stats-summary.test.sh — доказ, що поріг довіри agy рахується окремо для
# кожної моделі і саме так, як записано в orchestrator-autonomy.md §3.
#
# Що СПРАВЖНЄ: сам agy-stats-summary.sh. Що ПІДМІНЕНО: журнал — тут фікстура,
# у якій свідомо зібрано всі пастки справжнього agy-stats.md: `\|` усередині
# клітинки (на ньому 2026-09-23 розбився ручний підрахунок — колонки зсунулись),
# виклики до початку вікна, виклики з позначкою «не зараховано».
#
# Запуск: tools/scripts/agy-stats-summary.test.sh
set -uo pipefail

HERE="$(cd "$(dirname "$0")" && pwd)"
SCRIPT="$HERE/agy-stats-summary.sh"
fail=0
ok() { echo "✓ $1"; }
bad() {
  echo "✗ $1"
  fail=1
}

T="$(mktemp -d)"
trap 'rm -rf "$T"' EXIT

# Колонки як у справжньому журналі: дата | задача | модель | результат |
# вердикт | кейси | вигадки.
cat >"$T/stats.md" <<'MD'
# фікстура

| Дата       | Задача | Модель agy | Результат | Вердикт | Кейси | Вигадки |
| ---------- | ------ | ---------- | --------- | ------- | ----- | ------- |
| 2026-09-01 | до вікна | Model A | ok | так | 1/0 | **5** — до вікна, не рахується |
| 2026-09-16 | a1 | Model A | ok | так | 1/0 | **0** — чисто |
| 2026-09-17 | a2 `tail \| grep` у тексті | Model A | ok | так | 1/0 | **2** — дві вигадки |
| 2026-09-18 | a3 | Model A | timeout | n-a | n/a | **0** — **У вікно OQ-35 не зараховано** |
| 2026-09-19 | b1 | Model B | ok | так | 1/0 | **1** — одна |
| 2026-09-20 | b2 | Model B | ok | так | 1/0 | **3** — три |
MD

out="$(bash "$SCRIPT" "$T/stats.md" 2>&1)"
rc=$?
row() { grep -F "| $1 |" <<<"$out" | head -1; }

if ((rc == 0)); then ok "скрипт завершується з кодом 0"; else bad "скрипт впав (rc=$rc): $out"; fi

# Model A: у вікні 2 (a1, a2); a3 «не зараховано», запис до вікна — теж ні.
# З вигадками 1 з 2 → 50%, вигадок 2.
a="$(row 'Model A')"
if [[ "$a" == *"| 2 | 1 | 50% | 2 |"* ]]; then
  ok "Model A: 2 у вікні, 1 з вигадками, 50%, 2 вигадки — \`\\|\` у клітинці не зсунув колонки"
else
  bad "Model A порахована неправильно: '$a'"
fi

# Model B: 2 у вікні, обидва з вигадками → 100%, 4 вигадки.
b="$(row 'Model B')"
if [[ "$b" == *"| 2 | 2 | 100% | 4 |"* ]]; then
  ok "Model B: 2 у вікні, 2 з вигадками, 100%, 4 вигадки"
else
  bad "Model B порахована неправильно: '$b'"
fi

# Моделі, якої немає в журналі, у виводі бути не може — інакше таблиця
# вигадує дані сама.
if ! grep -qF 'Model C' <<<"$out"; then
  ok "у виводі лише моделі з журналу"
else
  bad "у виводі з'явилась модель, якої в журналі немає"
fi

# Вердикт порогу: до 10 викликів у вікні — рано судити; на 10+ — межа 50%.
{
  head -4 "$T/stats.md"
  for i in $(seq 10 19); do echo "| 2026-10-$i | c$i | Model C | ok | так | 1/0 | **$((i < 15 ? 1 : 0))** — x |"; done
  for i in $(seq 10 19); do echo "| 2026-10-$i | d$i | Model D | ok | так | 1/0 | **$((i < 16 ? 1 : 0))** — x |"; done
} >"$T/full.md"
full="$(bash "$SCRIPT" "$T/full.md" 2>&1)"
c="$(grep -F '| Model C |' <<<"$full")"
d="$(grep -F '| Model D |' <<<"$full")"
if [[ "$c" == *"| 10 | 5 | 50% |"* && "$c" == *"Розвідник"* ]]; then
  ok "10 викликів і рівно 50% → роль переходить у Розвідника (межа не «нижче 50%»)"
else
  bad "Model C (10 викликів, 50%) — вердикт неправильний: '$c'"
fi
if [[ "$d" == *"| 10 | 6 | 60% |"* && "$d" == *"Розвідник"* ]]; then
  ok "10 викликів і 60% → Розвідник"
else
  bad "Model D (10 викликів, 60%) — вердикт неправильний: '$d'"
fi
if [[ "$a" == *"рано"* ]]; then
  ok "менше 10 викликів у вікні → «рано судити»"
else
  bad "Model A (2 виклики) має вердикт «рано судити»: '$a'"
fi

# Межа саме 10, а не «скільки-небудь»: 9 викликів, усі з вигадками, — ще
# рано. Без цього випадку поріг 5 замість 10 проходив набір (мутація M5).
{
  head -4 "$T/stats.md"
  for i in $(seq 10 18); do echo "| 2026-10-$i | e$i | Model E | ok | так | 1/0 | **1** — x |"; done
} >"$T/nine.md"
e="$(bash "$SCRIPT" "$T/nine.md" 2>&1 | grep -F '| Model E |')"
if [[ "$e" == *"| 9 | 9 | 100% |"* && "$e" == *"рано"* ]]; then
  ok "9 викликів навіть зі 100% вигадок → ще «рано судити»: межа саме 10"
else
  bad "Model E (9 викликів, 100%) — вердикт неправильний: '$e'"
fi

# Маркер «не зараховано» діє лише в колонці вигадок — там, де його ставить
# журнал. Ті самі слова в описі задачі виклик із вікна НЕ викидають. Знайдено
# незалежним рев'ю (Gemini 3.1 Pro через agy) 2026-09-23: перша редакція
# шукала маркер у всьому рядку.
{
  head -4 "$T/stats.md"
  echo '| 2026-10-01 | Аналіз багу "платіж не зараховано" | Model F | ok | так | 1/0 | **1** — одна |'
} >"$T/marker.md"
f="$(bash "$SCRIPT" "$T/marker.md" 2>&1 | grep -F '| Model F |')"
if [[ "$f" == *"| 1 | 1 | 1 | 100% | 1 |"* ]]; then
  ok "«не зараховано» в описі задачі не викидає виклик із вікна"
else
  bad "виклик зі словами «не зараховано» в описі задачі випав із вікна: '$f'"
fi

# ─── Сумнів рахується проти моделі (рішення yurii 2026-09-23) ─────────────
# Виклик без підтвердженої моделі пишеться «невідомо → <модель за
# замовчуванням у момент виклику>». З вигадками — зараховується тій моделі:
# сумнів іде проти неї, а не на її користь. Чистий — не зараховується нікому:
# інакше невідомий виклик покращував би чужу статистику.
{
  head -4 "$T/stats.md"
  echo '| 2026-10-01 | g1 | Model G | ok | так | 1/0 | **0** — чисто |'
  echo '| 2026-10-02 | g2 невідомо з вигадками | невідомо → Model G | ok | так | 1/0 | **2** — дві |'
  echo '| 2026-10-03 | g3 невідомо чистий | невідомо → Model G | ok | так | 1/0 | **0** — чисто |'
  echo '| 2026-10-04 | g4 невідомо чистий без моделі | невідомо | ok | так | 1/0 | **0** — чисто |'
} >"$T/unknown.md"
u="$(bash "$SCRIPT" "$T/unknown.md" 2>&1)"
urc=$?
g="$(grep -F '| Model G |' <<<"$u")"
if [[ "$g" == *"| 2 | 2 | 1 | 50% | 2 |"* ]]; then
  ok "невідомий виклик із вигадками пішов у рахунок моделі за замовчуванням, чистий — ні"
else
  bad "Model G: очікувано 2 усього, 2 у вікні, 1 з вигадками, 50%, 2 вигадки — '$g'"
fi
if ((urc == 0)) && ! grep -qE '^\| невідомо' <<<"$u"; then
  ok "чисті невідомі виклики не з'являються окремою «моделлю» і не зараховуються нікому"
else
  bad "чистий невідомий виклик потрапив у таблицю або скрипт упав (rc=$urc): $(grep -E '^\| невідомо' <<<"$u")"
fi

# Невідомий виклик із вигадками, але без моделі за замовчуванням, — дірка в
# даних: сумнів нікому зарахувати. Скрипт мусить відмовити, а не мовчки
# викинути вигадки зі статистики.
{
  head -4 "$T/stats.md"
  echo '| 2026-10-05 | h1 | невідомо | ok | так | 1/0 | **1** — одна |'
} >"$T/orphan.md"
if orphan="$(bash "$SCRIPT" "$T/orphan.md" 2>&1)"; then
  bad "невідомий виклик із вигадками без моделі за замовчуванням пройшов мовчки: $orphan"
else
  if [[ "$orphan" == *"за замовчуванням"* ]]; then
    ok "невідомий виклик із вигадками без моделі за замовчуванням → відмова з поясненням"
  else
    bad "відмова без пояснення, що саме виправити: $orphan"
  fi
fi

# Запис «невідомо» стійкий до написання: велика літера і стрілка без пробілів
# — та сама непідтверджена модель, а не нова «модель» у таблиці. Знайдено
# рев'ю Gemini 3.1 Pro через agy 2026-09-23.
{
  head -4 "$T/stats.md"
  echo '| 2026-10-01 | k1 велика літера | Невідомо → Model K | ok | так | 1/0 | **1** — одна |'
  echo '| 2026-10-02 | k2 без пробілів | невідомо→Model K | ok | так | 1/0 | **1** — одна |'
} >"$T/spelling.md"
sp="$(bash "$SCRIPT" "$T/spelling.md" 2>&1)"
if [[ "$(grep -F '| Model K |' <<<"$sp")" == *"| 2 | 2 | 2 | 100% | 2 |"* ]] && ! grep -qiF 'невідомо' <<<"$sp"; then
  ok "«Невідомо» з великої і «невідомо→X» без пробілів — обидва в рахунку Model K"
else
  bad "написання «невідомо» зламало атрибуцію: $sp"
fi

# Порожньо після стрілки — моделі за замовчуванням не названо: відмова, а не
# «модель без назви».
{
  head -4 "$T/stats.md"
  echo '| 2026-10-03 | k3 | невідомо → | ok | так | 1/0 | **1** — одна |'
} >"$T/empty.md"
if bash "$SCRIPT" "$T/empty.md" >/dev/null 2>&1; then
  bad "«невідомо →» з порожньою моделлю і вигадками пройшов мовчки"
else
  ok "«невідомо →» з порожньою моделлю і вигадками → відмова"
fi

# Позначка «не зараховано» — для викликів БЕЗ тверджень (timeout, зонд). Вигадки
# в такому рядку — суперечність у даних; мовчки викинути їх із вікна означало б
# дати вигадкам зникнути. Скрипт мусить відмовити. Знайдено тим самим рев'ю.
{
  head -4 "$T/stats.md"
  echo '| 2026-10-04 | m1 | Model M | ok | так | 1/0 | **2** — **У вікно OQ-35 не зараховано** |'
} >"$T/contra.md"
if contra="$(bash "$SCRIPT" "$T/contra.md" 2>&1)"; then
  bad "вигадки в рядку «не зараховано» мовчки випали з вікна: $contra"
elif [[ "$contra" == *"не зараховано"* ]]; then
  ok "вигадки в рядку «не зараховано» → відмова з поясненням"
else
  bad "відмова без пояснення суперечності: $contra"
fi

# ─── Маркер — лише повна фраза «У вікно OQ-35 не зараховано» ───────────────
# 2026-09-24 справжній журнал: у колонці вигадок стояло «…не зараховано
# вигадкою», і виклик Opus тихо випав із вікна. Той самий клас, що й «маркер в
# усьому рядку» (рецензія Gemini 2026-09-23): маркер шукали ширше, ніж ставлять.
{
  head -4 "$T/stats.md"
  echo '| 2026-10-01 | q1 | Model Q | ok | так | 1/0 | **0** — одне твердження не зараховано вигадкою |'
  echo '| 2026-10-02 | q2 | Model Q | timeout | n-a | n/a | **0** — тверджень немає. **У вікно OQ-35 не зараховано** |'
} >"$T/phrase.md"
q="$(bash "$SCRIPT" "$T/phrase.md" 2>&1 | grep -F '| Model Q |')"
if [[ "$q" == *"| 2 | 1 | 0 |"* ]]; then
  ok "«не зараховано» у вільному тексті — виклик у вікні; повна фраза-маркер — ні"
else
  bad "маркер розпізнано неправильно: '$q'"
fi

# ─── Справжні знахідки — окрема колонка (рішення yurii 2026-09-24) ─────────
# Вигадки кажуть, скільки моделі не можна вірити; знахідки — скільки вона
# дала. Колонка йде ОСТАННЬОЮ, щоб не зсунути наявні. Рядки до її появи
# значення не мають — там «—», а не вигаданий нуль.
{
  echo '| Дата | Задача | Модель agy | Результат | Вердикт | Кейси | Вигадки | Справжніх знахідок |'
  echo '| - | - | - | - | - | - | - | - |'
  echo '| 2026-09-01 | до вікна | Model R | ok | так | 1/0 | **0** — x | 5 |'
  echo '| 2026-10-01 | r1 | Model R | ok | так | 1/0 | **0** — x | 1 — одна вада |'
  echo '| 2026-10-02 | r2 | Model R | ok | так | 1/0 | **1** — x | **2** — дві |'
  echo '| 2026-10-03 | r3 | Model R | ok | так | 1/0 | **0** — x | — |'
  echo '| 2026-10-04 | s1 | Model S | ok | так | 1/0 | **0** — x | — |'
} >"$T/real.md"
real="$(bash "$SCRIPT" "$T/real.md" 2>&1)"
r="$(grep -F '| Model R |' <<<"$real")"
s="$(grep -F '| Model S |' <<<"$real")"
if [[ "$r" == *"| 3 | 1 | 33% | 1 | 3 |"* ]]; then
  ok "справжні знахідки: 1 + 2 у вікні = 3; до вікна і «—» не рахуються"
else
  bad "справжні знахідки пораховано неправильно: '$r'"
fi
if [[ "$s" == *"| 1 | 0 | 0% | 0 | — |"* ]]; then
  ok "модель лише з «—» у колонці знахідок → «—», а не 0"
else
  bad "лише «—» у колонці знахідок мав дати «—»: '$s'"
fi

# ─── Контрприклади другої рецензії (Gemini 3.8 Flash High, 2026-09-24) ──────
H8='| Дата | Задача | Модель agy | Результат | Вердикт | Кейси | Вигадки | Справжніх знахідок |
| - | - | - | - | - | - | - | - |'

# КП3. Іспит — ПЕРШІ 10 викликів моделі, і вердикт після них остаточний
# (docs/20 OQ-35: «наступні 10 викликів»; правило не переглядається заднім
# числом). Перша редакція рахувала всі виклики, тож модель, що не склала
# іспиту, «відмивалась» чистими викликами Розвідника до «Рев'юер тримається».
{
  echo "$H8"
  for i in $(seq 10 19); do echo "| 2026-10-$i | y | Model Y | ok | так | 1/0 | **$((i < 15 ? 1 : 0))** — x | — |"; done
  for i in $(seq 20 24); do echo "| 2026-10-$i | y | Model Y | ok | так | 1/0 | **0** — x | — |"; done
} >"$T/exam.md"
y="$(bash "$SCRIPT" "$T/exam.md" 2>&1 | grep -F '| Model Y |')"
if [[ "$y" == *"| 15 | 10 | 5 | 50% |"* && "$y" == *"Розвідник"* && "$y" == *"поза іспитом: 5"* ]]; then
  ok "іспит — перші 10 викликів: 5 чистих після нього вердикт «Розвідник» не скасовують"
else
  bad "виклики після іспиту змінили вердикт: '$y'"
fi

# КП1. Сумнів — проти моделі, не на її користь: невідомий виклик із
# вигадками йде в її вікно й вигадки, але його знахідки їй НЕ зараховуються.
{
  echo "$H8"
  echo '| 2026-10-01 | g1 | Model G | ok | так | 1/0 | **0** — x | **1** — одна |'
  echo '| 2026-10-02 | g2 | невідомо → Model G | ok | так | 1/0 | **2** — дві | **5** — п’ять |'
} >"$T/borrow.md"
g2="$(bash "$SCRIPT" "$T/borrow.md" 2>&1 | grep -F '| Model G |')"
if [[ "$g2" == *"| 2 | 2 | 1 | 50% | 2 | 1 |"* ]]; then
  ok "невідомий виклик: вигадки — проти моделі, знахідки — не на її користь"
else
  bad "невідомий виклик покращив знахідки моделі: '$g2'"
fi

# КП2. Число вигадок без жирного — однаково число; а рядок у вікні зовсім без
# числа й без маркера — відмова, а не тихий пропуск з іспиту.
{
  echo "$H8"
  echo '| 2026-10-01 | p1 | Model P | ok | так | n/a | 1 — одна вигадка | — |'
} >"$T/plain.md2"
p="$(bash "$SCRIPT" "$T/plain.md2" 2>&1 | grep -F '| Model P |')"
if [[ "$p" == *"| 1 | 1 | 1 | 100% | 1 |"* ]]; then
  ok "«1 — …» без жирного — однаково число вигадок, виклик в іспиті"
else
  bad "число вигадок без ** пропущено: '$p'"
fi
{
  echo "$H8"
  echo '| 2026-10-01 | p2 | Model P | ok | так | n/a | вигадок не рахували | — |'
} >"$T/nonum.md"
if nonum="$(bash "$SCRIPT" "$T/nonum.md" 2>&1)"; then
  bad "рядок у вікні без числа вигадок пройшов мовчки: $nonum"
else
  ok "рядок у вікні без числа вигадок і без маркера → відмова"
fi

# ─── Кількість клітинок у рядку = кількості колонок шапки ──────────────────
# Неекранований `|` у тексті клітинки зсуває ВСІ колонки праворуч: модель,
# вигадки і знахідки читаються з чужих місць, мовчки. Знайдено рецензією
# Claude Opus 4.6 через agy 2026-09-24. Такий рядок — відмова, а не число.
{
  head -4 "$T/stats.md"
  echo '| 2026-10-01 | x1 зламаний | текст | Model X | ok | так | 1/0 | **0** — x |'
} >"$T/shift.md"
if shift_out="$(bash "$SCRIPT" "$T/shift.md" 2>&1)"; then
  bad "рядок із зайвою клітинкою прийнято мовчки: $shift_out"
elif [[ "$shift_out" == *"клітинок"* ]]; then
  ok "рядок із зайвим «|» → відмова з поясненням про кількість клітинок"
else
  bad "відмова без пояснення: $shift_out"
fi
if head -1 <<<"$real" | grep -qF '| Знахідок | Вердикт |'; then
  ok "шапка: «Знахідок» стоїть перед «Вердикт»"
else
  bad "шапка без колонки «Знахідок»: $(head -1 <<<"$real")"
fi

# Контроль сили: той самий журнал без `\|` у клітинці дає ті самі числа.
# Якщо ні — перевірка вище пройшла випадково.
sed 's/ \\| / /' "$T/stats.md" >"$T/plain.md"
plain="$(bash "$SCRIPT" "$T/plain.md" 2>&1 | grep -F '| Model A |')"
if [[ -n "$a" && "$plain" == "$a" ]]; then
  ok "контроль: з \`\\|\` і без нього рядок Model A однаковий"
else
  bad "контроль: \`\\|\` змінює результат — '$a' проти '$plain'"
fi

if ((fail)); then
  echo "Провалено."
  exit 1
fi
echo "Усі тести пройдено."
