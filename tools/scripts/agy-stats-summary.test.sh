    mutate "тека не читається" '[[ -d "$dir" ]] || return 0' 'return 0' lib
    mutate "порядок файлів — за іменем, а не за потраплянням у main" 'sorted="$(journal_order "$dir" "${names[@]}")" || return 2' 'sorted="$(printf '"'"'%s\n'"'"' "${names[@]}" | LC_ALL=C sort)"' lib
