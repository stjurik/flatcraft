mkdir -p "$T/merged"
{
  echo "$H8"
  H8ROW 2026-10-01 a1 'Model V' '**1** — x' 1
  H8ROW 2026-10-03 a2 'Model V' '**0** — x' '—'
  H8ROW 2026-10-04 c1 'Model W' '**2** — x' 1
  H8ROW 2026-10-02 b1 'Model V' '**1** — x' '**2** — дві'
  H8ROW 2026-10-02 b2 'Model W' '**0** — x' '—'
